// Only operational settings needed by the local processes may reach framework caches.
const allowed = new Set([
  'PATH',
  'HOME',
  'USERPROFILE',
  'HOMEDRIVE',
  'HOMEPATH',
  'APPDATA',
  'LOCALAPPDATA',
  'PROGRAMDATA',
  'SYSTEMROOT',
  'WINDIR',
  'COMSPEC',
  'PATHEXT',
  'TEMP',
  'TMP',
  'TMPDIR',
  'LANG',
  'LC_ALL',
  'LC_CTYPE',
  'TZ',
  'TERM',
  'COLORTERM',
  'CI',
  'NO_COLOR',
  'FORCE_COLOR',
  'PNPM_HOME',
  'NODE_ENV',
  'NODE_OPTIONS',
  'NPM_CONFIG_USER_AGENT',
  'XDG_RUNTIME_DIR',
  'XDG_CONFIG_HOME',
  'XDG_DATA_HOME',
  'XDG_CACHE_HOME',
  'DOCKER_HOST',
  'DOCKER_CONTEXT',
  'DOCKER_CONFIG',
  'DOCKER_TLS_VERIFY',
  'DOCKER_CERT_PATH',
  'PROOFSEC_ROOT_DIR',
  'PROOFSEC_DATA_DIR',
  'PROOFSEC_ORIGIN',
]);

export function childEnvironment(source = process.env) {
  return {
    ...Object.fromEntries(Object.entries(source).filter(([key]) => allowed.has(key.toUpperCase()))),
    NEXT_TELEMETRY_DISABLED: '1',
  };
}
